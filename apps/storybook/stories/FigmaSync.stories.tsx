import type { Meta, StoryObj } from '@storybook/react';
import type * as React from 'react';
import { Badge } from '@helix-ds/core';
import type { BadgeVariant } from '@helix-ds/core';
import { StoryHeader } from './_shared/StoryHeader';
import figmaSync from '../../../contracts/figma-sync.json';

const meta: Meta = {
  title: 'Figma Sync',
  tags: ['autodocs'],
  parameters: {
    layout: 'padded',
    docs: {
      description: {
        story: 'Component x Figma sync matrix, read from `contracts/figma-sync.json` — whether each component is modeled in Figma, whether its variants match the code, and whether its Figma variable bindings match `component.*` tokens.',
      },
    },
  },
};

export default meta;
type Story = StoryObj;

type TriState = boolean | null;

const TRISTATE_VARIANT: Record<string, BadgeVariant> = {
  yes: 'success',
  no: 'danger',
  unknown: 'neutral',
};

function TriBadge({ value, yesLabel, noLabel }: { value: TriState; yesLabel: string; noLabel: string }) {
  if (value === null) {
    return <Badge variant={TRISTATE_VARIANT.unknown} label="—" />;
  }
  return <Badge variant={value ? TRISTATE_VARIANT.yes : TRISTATE_VARIANT.no} label={value ? yesLabel : noLabel} />;
}

const TH_STYLE: React.CSSProperties = {
  textAlign: 'left',
  padding: '8px 12px',
  fontSize: 11,
  fontWeight: 600,
  letterSpacing: '0.04em',
  textTransform: 'uppercase',
  color: 'var(--helix-color-text-neutral-lightest)',
  borderBottom: '1px solid var(--helix-color-border-neutral)',
};

const TD_STYLE: React.CSSProperties = {
  padding: '8px 12px',
  fontSize: 13,
  borderBottom: '1px solid var(--helix-color-border-neutral-light)',
  color: 'var(--helix-color-text-neutral)',
  verticalAlign: 'top',
};

export const Overview: Story = {
  render: () => {
    const rows = [...figmaSync.components].sort((a, b) => a.name.localeCompare(b.name));
    const inFigmaCount = rows.filter(r => r.inFigma).length;

    return (
      <div>
        <StoryHeader
          title="Figma Sync"
          description={`${inFigmaCount} of ${rows.length} components are modeled in Figma. This table is hand-recorded, not auto-generated — see the file's own "howToRefresh" for how a check gets run and updated.`}
        />

        <p style={{
          margin: '0 0 var(--helix-spacing-l)',
          fontSize: 'var(--helix-textStyle-caption-regular-fontSize)',
          color: 'var(--helix-color-text-neutral-lightest)',
        }}>
          Source file:{' '}
          <a
            href={figmaSync.figmaFileUrl}
            target="_top"
            rel="noopener noreferrer"
            style={{ color: 'var(--helix-color-text-neutral-lightest)' }}
          >
            {figmaSync.figmaFileKey}
          </a>
          {' '}— unlike <code>contracts/manifest.json</code>, this file can't be regenerated by a local script
          (no Figma REST token is configured in this repo); checks are run through an agent with Figma access
          and recorded here by hand.
        </p>

        <div style={{ overflowX: 'auto' }}>
          <table style={{ width: '100%', borderCollapse: 'collapse' }}>
            <thead>
              <tr>
                <th style={TH_STYLE}>Component</th>
                <th style={TH_STYLE}>In Figma</th>
                <th style={TH_STYLE}>Variants match</th>
                <th style={TH_STYLE}>Tokens match</th>
                <th style={TH_STYLE}>Last checked</th>
                <th style={TH_STYLE}>Notes</th>
              </tr>
            </thead>
            <tbody>
              {rows.map(r => (
                <tr key={r.name}>
                  <td style={{ ...TD_STYLE, fontWeight: 500 }}>{r.name}</td>
                  <td style={TD_STYLE}>
                    <TriBadge value={r.inFigma} yesLabel="yes" noLabel="no" />
                  </td>
                  <td style={TD_STYLE}>
                    <TriBadge value={r.variantsMatch as TriState} yesLabel="match" noLabel="drift" />
                  </td>
                  <td style={TD_STYLE}>
                    <TriBadge value={r.tokensMatch as TriState} yesLabel="match" noLabel="drift" />
                  </td>
                  <td style={TD_STYLE}>{r.lastChecked ?? '—'}</td>
                  <td style={{ ...TD_STYLE, maxWidth: 420, fontSize: 12, color: 'var(--helix-color-text-neutral-light)' }}>
                    {r.notes}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </div>
    );
  },
};
