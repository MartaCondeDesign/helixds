/**
 * `pnpm figma:story-order` — read every component's prop order exactly as Storybook shows it (the Controls / props
 * table on its docs page) and write .ai/storybook-prop-order.json. That order is the reference for Figma's property
 * order (contracts/figma-conversion.json → propertyOrder): not the contract, not the .types.ts file — Storybook
 * reorders them (required first, args, argTypes…), and the owner compares Figma against what Storybook shows.
 * Needs Storybook running (STORYBOOK_URL, default http://localhost:6006). `pnpm docs:figma-map` reads the file.
 */
import fs from 'fs';
import path from 'path';
import { chromium } from 'playwright';

async function main() {
const url = process.env.STORYBOOK_URL ?? 'http://localhost:6006';
const out = path.resolve(import.meta.dirname, '../../.ai/storybook-prop-order.json');
const index = await (await fetch(`${url}/index.json`)).json() as { entries: Record<string, { id: string; title: string; type: string }> };
const docs = Object.values(index.entries).filter(e => e.type === 'docs' && /^(Components|Layout)\//.test(e.title));
const browser = await chromium.launch();
const page = await browser.newPage();
const order: Record<string, string[]> = {};
for (const d of docs) {
  const name = d.title.split('/').pop()!;
  await page.goto(`${url}/iframe.html?viewMode=docs&id=${d.id}`);
  await page.waitForSelector('.docblock-argstable tbody tr', { timeout: 20000 }).catch(() => null);
  // the first props table on the page is the component's Controls table; category rows (EVENTS…) are skipped
  order[name] = await page.evaluate(() => {
    const table = document.querySelector('.docblock-argstable');
    if (!table) return [];
    return [...table.querySelectorAll('tbody tr')]
      .filter(tr => tr.querySelectorAll('td').length > 1)
      .map(tr => (tr.querySelector('td')?.textContent ?? '').replace(/\*$/, '').trim())
      .filter(n => /^[\w-]+$/.test(n));
  });
}
await browser.close();
fs.writeFileSync(out, JSON.stringify({ $comment: 'GENERATED by pnpm figma:story-order from the running Storybook — each component\'s props in the order its docs page lists them. The reference for Figma\'s property order.', components: order }, null, 2) + '\n');
console.log(`✅ .ai/storybook-prop-order.json — ${Object.keys(order).length} components`);
}
main().catch(e => { console.error(e); process.exit(1); });
